def applyMetaLogic(side, conf, history):
    if len(history) < 6: return side, conf, None
    last = history[-1]
    streak = 0
    for x in reversed(history):
        if x == last: streak += 1
        else: break
    if streak >= 8:
        new_side = "X" if last == "T" else "T"
        return new_side, 90.0, f"Phát hiện bệt {streak} tay -> Lệnh bẻ cầu"
    return side, conf, None
